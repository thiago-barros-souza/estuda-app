/// Retorna as questões de Conhecimentos Específicos para o cargo informado.
List<Question> getSpecificQuestionsForRole(String roleId) {
  if (roleId == 'tecnico_enfermagem') {
    return allQuestions.where((q) => q.subject == 'especificas').toList();
  }
  return roleSpecificQuestions[roleId] ?? [];
}

/// Retorna o pool completo de questões (gerais + específicas) para o cargo,
/// respeitando as disciplinas do edital (ex.: Nível Superior não possui Informática).
List<Question> getQuestionsForRole(JobRole role) {
  final specific = getSpecificQuestionsForRole(role.id);
  final general = allQuestions.where((q) {
    if (q.subject == 'especificas') return false;
    if (role.isSuperior && q.subject == 'informatica') return false;
    return true;
  }).toList();

  return [...general, ...specific];
}
